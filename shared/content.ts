/** 현재 상황에서 보여 줄 카드 목록 (사건 사례 → 공통 → 국가별 순) */
export function cardsFor(round: number, country?: CountryId): Card[] {
  const rd = Math.min(Math.max(round, 0), 5);
  const list = CARDS.filter((c) => (c.kind !== 'country' && c.round === rd) || (c.kind === 'country' && c.country === country));
  if (rd === 0) return list;
  // 국가 카드는 라운드에 따라 번갈아 앞에 오도록 정렬
  const own = list.filter((c) => c.kind === 'country');
  const rest = list.filter((c) => c.kind !== 'country');
  if (own.length > 1 && rd % 2 === 0) own.reverse();
  return [...rest.filter((c) => c.kind === 'common').slice(0, 1), ...rest.filter((c) => c.kind === 'case'), ...own.slice(0, 1), ...rest.filter((c) => c.kind === 'common').slice(1), ...own.slice(1)];
}

/** 지금까지 접한 학습 개념 (보고서용) */
export function learnedCards(round: number, country?: CountryId): Card[] {
  return CARDS.filter((c) => (c.kind === 'country' ? c.country === country : (c.round ?? 0) <= round));
}
